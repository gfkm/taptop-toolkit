const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const { nextAction } = require('../lib/next-action');
const { buildArtifact } = require('../lib/build-artifact');
const { addArtifact } = require('../lib/project-artifacts');
const { recordCheck } = require('../lib/record-check');
const { initProject } = require('../lib/project');
const { writeUiKit } = require('../lib/ui-kit/write');
const { tempWorkspace, managedProject, pageHtml, write, KIT_DATA, ROLE_CSS } = require('../test-support/managed-project');

test('the next step follows the project from empty to verified, one action at a time', async t => {
  const workspace = tempWorkspace(t);
  const root = path.join(workspace, 'projects/flow-site');
  initProject(root, 'flow-site');
  assert.equal(nextAction(root).action, 'prepare-ui-kit-data');
  write(root, 'design-system/kit.json', JSON.stringify(KIT_DATA));
  write(root, 'design-system/roles.css', ROLE_CSS);
  const generate = nextAction(root);
  assert.equal(generate.action, 'generate-ui-kit');
  assert.match(generate.command, /ui-kit projects\/flow-site --data design-system\/kit\.json/);
  writeUiKit(root, { data: 'design-system/kit.json' });
  const buildKit = nextAction(root);
  assert.deepEqual([buildKit.action, buildKit.artifact], ['build', 'ui-kit']);
  await buildArtifact({ projectRoot: root, artifactKey: 'ui-kit' });
  write(root, 'input/home/index.html', pageHtml('home-page'));
  write(root, 'input/home/styles.css', '.home-page { display: flex; }');
  addArtifact(root, { key: 'pages/home', html: 'input/home/index.html', stylesheets: ['design-system/roles.css', 'input/home/styles.css'], dependsOn: ['ui-kit'] });
  assert.deepEqual([nextAction(root).action, nextAction(root).artifact], ['build', 'pages/home']);
  await buildArtifact({ projectRoot: root, artifactKey: 'pages/home' });
  const compare = nextAction(root);
  assert.deepEqual([compare.action, compare.artifact], ['check-local', 'ui-kit'], 'checks follow dependency order');
  assert.match(compare.command, /check --project projects\/flow-site --artifact ui-kit --level local/);
  assert.match(compare.compare || '', /normalize-compare\.html\?original=/);
  recordCheck({ projectRoot: root, artifactKey: 'pages/home', level: 'local', result: 'passed', note: '8 widths' });
  recordCheck({ projectRoot: root, artifactKey: 'ui-kit', level: 'local', result: 'passed', note: '8 widths' });
  const importStep = nextAction(root);
  assert.deepEqual([importStep.action, importStep.artifact], ['import-and-check-editor', 'ui-kit']);
  recordCheck({ projectRoot: root, artifactKey: 'ui-kit', level: 'editor', result: 'passed', note: '4 canvases' });
  recordCheck({ projectRoot: root, artifactKey: 'pages/home', level: 'editor', result: 'passed', note: '4 canvases' });
  assert.equal(nextAction(root).action, 'done');
});

test('a failed check, a stale dependency and a blocking issue come before anything else', async t => {
  const { root } = managedProject(t);
  await buildArtifact({ projectRoot: root, artifactKey: 'ui-kit' });
  recordCheck({ projectRoot: root, artifactKey: 'ui-kit', level: 'local', result: 'failed', note: 'button 2px lower at 768' });
  const fix = nextAction(root);
  assert.deepEqual([fix.action, fix.artifact], ['fix-failed-check', 'ui-kit']);
  write(root, 'input/home/index.html', pageHtml('home-page'));
  write(root, 'input/home/styles.css', '.home-page { display: flex; }');
  addArtifact(root, { key: 'pages/home', html: 'input/home/index.html', stylesheets: ['design-system/roles.css', 'input/home/styles.css'], dependsOn: ['ui-kit'] });
  fs.appendFileSync(path.join(root, 'design-system/roles.css'), '\n.text-link { color: #223344; }\n');
  writeUiKit(root, { data: 'design-system/kit.json', replace: true });
  const order = nextAction(root);
  assert.deepEqual([order.action, order.artifact], ['build', 'ui-kit'], 'the UI kit is rebuilt before the page that depends on it');
  fs.rmSync(path.join(root, 'input/home/styles.css'));
  const blocked = nextAction(root);
  assert.equal(blocked.action, 'fix');
  assert.equal(blocked.code, 'ARTIFACT_SOURCE_MISSING');
});
